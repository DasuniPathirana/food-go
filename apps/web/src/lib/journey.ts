import { z } from "zod";
import { gameProfileSchema } from "./game-profile";
import { buildingPresetSchema, mallDirectorySchema } from "./world-data";

export const accountTypeSchema = z.enum(["explorer", "partner"]);
export const customerAction = z.discriminatedUnion("action", [
  z.strictObject({ action: z.literal("save"), kind: z.enum(["venue", "dish"]), id: z.uuid(), saved: z.boolean() }),
  z.strictObject({ action: z.literal("redeem"), code: z.string().trim().toLowerCase().regex(/^[a-f0-9]{32}$/u) }),
  z.strictObject({ action: z.literal("account"), accountType: accountTypeSchema }),
]);
const time = z.iso.datetime({ offset: true });
export const journeySchema = z.object({
  progress: gameProfileSchema,
  accountType: accountTypeSchema,
  displayName: z.string(),
  savedVenues: z.array(z.uuid()).max(100),
  savedDishes: z.array(z.uuid()).max(100),
  visits: z.array(z.object({ id: z.uuid(), name: z.string(), suburb: z.string(), at: time })).max(500),
  discoveries: z.array(z.object({ id: z.uuid(), name: z.string(), venue: z.string(), cuisine: z.string(), at: time })).max(500),
});
export type Journey = z.infer<typeof journeySchema>;

export const partnerAction = z.discriminatedUnion("action", [
  z.strictObject({ action: z.literal("submit"), venueId: z.uuid(), version: time }),
  z.strictObject({
    action: z.literal("details"),
    venueId: z.uuid(),
    version: time,
    name: z.string().trim().min(2).max(120),
    description: z.string().max(1000),
    venueType: z.enum(["restaurant", "cafe", "market", "bakery", "food_truck"]).optional(),
    cuisine: z.string().trim().min(2).max(60),
    address: z.string().trim().min(5).max(200),
    suburb: z.string().trim().min(2).max(100),
    state: z.enum(["ACT", "NSW", "NT", "QLD", "SA", "TAS", "VIC", "WA"]),
    postcode: z.string().regex(/^\d{4}$/u),
    gameEnabled: z.boolean(),
  }),
  z.strictObject({
    action: z.literal("dish"),
    venueId: z.uuid(),
    dishId: z.uuid(),
    version: time.optional(),
    name: z.string().trim().min(2).max(120),
    description: z.string().max(1000),
    price: z.number().int().min(0).max(1000000),
    available: z.boolean(),
    imageUrl: z.string().nullish(),
  }),
  z.strictObject({ action: z.literal("issue"), venueId: z.uuid(), dishId: z.uuid().optional() }),
  z.strictObject({
    action: z.literal("promo"),
    venueId: z.uuid(),
    id: z.uuid(),
    title: z.string().trim().min(2).max(90),
    description: z.string().trim().min(2).max(400),
    startsAt: time,
    endsAt: time,
    kind: z.enum(["food", "restaurant", "cafe"]).optional(),
    badgeText: z.string().optional(),
    imageUrl: z.string().nullish(),
  }),
]);

export const workspaceBuildingProposalSchema = z.object({
  venue_id: z.uuid().optional(),
  proposed_latitude: z.number().nullish(),
  proposed_longitude: z.number().nullish(),
  proposed_mall_id: z.uuid().nullish(),
  proposed_floor: z.string().nullish(),
  proposed_unit: z.string().nullish(),
  proposed_building_preset: buildingPresetSchema.nullish(),
  proposed_accent_colour: z.string().nullish(),
  proposed_signage: z.string().nullish(),
  review_status: z.enum(["pending", "approved", "rejected"]).nullish(),
  review_note: z.string().nullish(),
  submitted_at: z.string().nullish(),
});

export const workspaceLootSchema = z.object({
  id: z.uuid(),
  title: z.string(),
  description: z.string(),
  grabMode: z.enum(["map_grab", "ar_grab"]),
  rewardKind: z.enum(["collectible", "offer", "xp_coins"]),
  modelStyle: z.enum(["golden_crystal", "mystery_ring", "reward_crate", "dish_trophy", "star_chest"]),
  rarity: z.enum(["common", "rare", "epic", "legendary"]),
  xpReward: z.number().int(),
  coinReward: z.number().int(),
  status: z.string(),
  reviewNote: z.string().nullish(),
  claimedCount: z.number().int().default(0),
  maxClaims: z.number().int().default(250),
  latitude: z.number().nullish(),
  longitude: z.number().nullish(),
  startsAt: z.string().nullish(),
  endsAt: z.string().nullish(),
});

export const workspaceSchema = z.object({
  venue: z.object({
    id: z.uuid(),
    name: z.string(),
    description: z.string(),
    venue_type: z.enum(["restaurant", "cafe", "market", "bakery", "food_truck"]).default("restaurant"),
    cuisine: z.string(),
    address: z.string(),
    suburb: z.string(),
    state: z.string(),
    postcode: z.string(),
    latitude: z.number().nullish(),
    longitude: z.number().nullish(),
    status: z.enum(["draft", "pending", "published", "suspended"]),
    ownership_verified_at: z.string().nullable(),
    game_enabled: z.boolean(),
    updated_at: time,
    cover_image_url: z.string().nullish(),
    building_preset: buildingPresetSchema.default("city-bistro"),
    building_accent_colour: z.string().default("#00c49a"),
    building_signage: z.string().nullish(),
    building_review_status: z.enum(["none", "pending", "approved", "rejected"]).default("none"),
    mall_id: z.uuid().nullish(),
    mall_floor: z.string().nullish(),
    mall_unit: z.string().nullish(),
    reservations_enabled: z.boolean().default(true),
    reservation_notes: z.string().nullish(),
  }),
  buildingProposal: workspaceBuildingProposalSchema.nullish(),
  malls: z.array(mallDirectorySchema).default([]),
  contact: z.object({ email: z.string().nullish(), phone: z.string().nullish() }).nullish(),
  dishes: z.array(z.object({
    id: z.uuid(),
    name: z.string(),
    description: z.string(),
    price_aud_cents: z.number().nullable(),
    is_available: z.boolean(),
    image_url: z.string().nullish(),
    updated_at: time,
  })).max(100),
  promotions: z.array(z.object({
    id: z.uuid(),
    title: z.string(),
    description: z.string().nullish(),
    status: z.string(),
    starts_at: z.string().nullish(),
    ends_at: time,
    kind: z.enum(["food", "restaurant", "cafe"]).default("restaurant"),
    badge_text: z.string().nullish(),
    image_url: z.string().nullish(),
  })).max(100),
  loots: z.array(workspaceLootSchema).default([]),
  visits: z.number().int().nonnegative(),
  discoveries: z.number().int().nonnegative(),
  pendingReservations: z.number().int().nonnegative().default(0),
});
export type Workspace = z.infer<typeof workspaceSchema>;
